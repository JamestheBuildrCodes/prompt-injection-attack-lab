"""Report generation: JSON, CSV and PDF."""
from __future__ import annotations

import csv
import io
import json
import re
from datetime import datetime, timezone
from xml.sax.saxutils import escape

from attacks.library import CATEGORIES
from config.settings import APP_NAME, SEVERITIES, VERSION

DISCLAIMER = ("Generated by the Prompt Injection Attack Lab against the configured target only. Probes use synthetic "
              "canaries and harmless markers. Findings are heuristic: 'confirmed' means a deterministic indicator was "
              "observed, 'suspected' means partial evidence, 'inconclusive' means manual review is needed.")
CSV_FIELDS = ["case_id", "category", "name", "status", "severity", "finding_type", "confidence", "refused",
              "marker_found", "canary_exposed", "prompt_overlap", "latency_ms", "title", "evidence", "recommendation", "response"]


def _sev_rank(s: str) -> int:
    return SEVERITIES.index(s) if s in SEVERITIES else 0


def build_report(assessment: dict, results: list[dict]) -> dict:
    findings = sorted([r for r in results if r["status"] in ("confirmed", "suspected", "inconclusive")],
                      key=lambda r: (-{"confirmed": 3, "suspected": 2, "inconclusive": 1}[r["status"]], -_sev_rank(r["severity"])))
    recs: dict[str, dict] = {}
    for r in findings:
        if r["status"] == "inconclusive" and not r.get("recommendation"):
            continue
        key = r.get("recommendation") or ""
        if key:
            recs.setdefault(key, {"recommendation": key, "affected_cases": []})["affected_cases"].append(r["case_id"])
    target = dict(assessment.get("target", {}))
    for secret_key in ("api_key", "apikey", "authorization", "token"):  # defence in depth
        target.pop(secret_key, None)
    return {
        "report": {"title": f"{APP_NAME} security report", "tool_version": VERSION,
                   "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds")},
        "assessment": {"id": assessment.get("id"), "name": assessment.get("name"),
                       "test_date": assessment.get("created_at"), "finished_at": assessment.get("finished_at")},
        "target_configuration": target,
        "summary": assessment.get("score") or {},
        "findings": [{k: r.get(k) for k in ("case_id", "category", "name", "status", "severity", "finding_type", "title",
                                              "rationale", "confidence", "evidence", "recommendation")} for r in findings],
        "test_cases": [{k: r.get(k) for k in ("case_id", "category", "name", "status", "severity", "prompt", "response",
                                                "refused", "marker_found", "canary_hits", "latency_ms", "techniques")}
                       for r in results],
        "recommendations": list(recs.values()),
        "disclaimer": DISCLAIMER,
    }


def report_to_json(report: dict) -> str:
    return json.dumps(report, indent=2, ensure_ascii=False)


def _csv_safe(value) -> str:
    """Neutralise spreadsheet formula injection: model output is untrusted."""
    s = "" if value is None else str(value)
    return "'" + s if s[:1] in ("=", "+", "-", "@", "\t", "\r") else s


def results_to_csv(results: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=CSV_FIELDS)
    w.writeheader()
    for r in results:
        w.writerow({k: _csv_safe(v) for k, v in {
            "case_id": r["case_id"], "category": r["category"], "name": r["name"], "status": r["status"],
            "severity": r["severity"], "finding_type": r.get("finding_type", ""), "confidence": r.get("confidence", ""),
            "refused": r.get("refused", ""), "marker_found": r.get("marker_found", ""),
            "canary_exposed": ";".join(h["name"] for h in r.get("canary_hits", [])),
            "prompt_overlap": r.get("overlap", ""), "latency_ms": r.get("latency_ms", ""), "title": r.get("title", ""),
            "evidence": " | ".join(r.get("evidence", [])), "recommendation": r.get("recommendation", ""),
            "response": (r.get("response") or "").replace("\r", " ").replace("\n", " ")[:2000]}.items()})
    return buf.getvalue()


def _clean(text, limit: int = 600) -> str:
    s = re.sub(r"[\x00-\x08\x0b-\x1f\u200b-\u200f\u2060\ufeff]", "", str(text or ""))
    s = s.encode("latin-1", "replace").decode("latin-1")  # built-in PDF fonts are latin-1
    return escape(s[:limit] + ("..." if len(s) > limit else "")).replace("\n", "<br/>")


def report_to_pdf(report: dict) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], fontSize=20, alignment=0, spaceAfter=4)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], spaceBefore=12, spaceAfter=4)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=9, leading=12)
    mono = ParagraphStyle("m", parent=body, fontName="Courier", fontSize=8, leading=10, backColor=colors.HexColor("#EEF1F0"))
    status_color = {"confirmed": "#B3261E", "suspected": "#B26A00", "inconclusive": "#5B6B7B", "resisted": "#1F7A5A"}

    summ, meta, tgt = report["summary"], report["assessment"], report["target_configuration"]
    sc = summ.get("status_counts", {})
    out = io.BytesIO()
    doc = SimpleDocTemplate(out, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title=report["report"]["title"], author=APP_NAME)
    s: list = [Paragraph(_clean(report["report"]["title"]), h1),
               Paragraph(f"Assessment: {_clean(meta['name'])} &nbsp; | &nbsp; Test date: {_clean(meta['test_date'])} &nbsp; | &nbsp; Tool v{report['report']['tool_version']}", body),
               Spacer(1, 6)]
    s.append(Paragraph("Summary", h2))
    rows = [["Overall security score", f"{summ.get('overall_score', 'n/a')} / 100 (grade {summ.get('grade', 'n/a')})"],
            ["Attack cases / controls", f"{summ.get('attack_cases', 0)} / {summ.get('control_cases', 0)}"],
            ["Confirmed / suspected / inconclusive / resisted", " / ".join(str(sc.get(k, 0)) for k in ("confirmed", "suspected", "inconclusive", "resisted"))],
            ["Attack success rate", f"{summ.get('attack_success_rate', 0):.0%}"],
            ["Refusal rate", f"{summ.get('refusal_rate', 0):.0%}"],
            ["Canary exposures", str(summ.get("canary_exposure_count", 0))],
            ["Instruction-following vulnerability rate", f"{summ.get('instruction_following_vulnerability_rate', 0):.0%}"],
            ["False refusal rate (benign controls)", f"{summ.get('false_refusal_rate', 0):.0%}"]]
    for note in summ.get("caps_applied", []):
        rows.append(["Score cap", note])
    t = Table([[Paragraph(_clean(a), body), Paragraph(_clean(b), body)] for a, b in rows], colWidths=[75 * mm, 95 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#B8C2BD")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    s.append(t)

    s.append(Paragraph("Target configuration", h2))
    s.append(Paragraph(_clean(json.dumps(tgt, indent=1)), mono))

    s.append(Paragraph(f"Findings ({len(report['findings'])})", h2))
    if not report["findings"]:
        s.append(Paragraph("No confirmed, suspected or inconclusive findings.", body))
    for f in report["findings"]:
        col = status_color.get(f["status"], "#333333")
        block = [Paragraph(f'<font color="{col}"><b>{f["status"].upper()}</b></font> &nbsp; <b>{_clean(f["case_id"])}</b> {_clean(f["title"])} '
                           f'&nbsp; (severity: {_clean(f["severity"])}, confidence {f.get("confidence", 0):.0%})', body),
                 Paragraph(_clean(f.get("rationale")), body)]
        for e in f.get("evidence") or []:
            block.append(Paragraph("Evidence: " + _clean(e, 300), mono))
        if f.get("recommendation"):
            block.append(Paragraph("<b>Recommendation:</b> " + _clean(f["recommendation"], 400), body))
        block.append(Spacer(1, 6))
        s.append(KeepTogether(block))

    s.append(Paragraph("Recommendations", h2))
    for r in report["recommendations"] or [{"recommendation": "No remediation needed for the cases tested.", "affected_cases": []}]:
        s.append(Paragraph(f"- {_clean(r['recommendation'], 500)} <i>({_clean(', '.join(r['affected_cases']))})</i>", body))

    s.append(Paragraph("All test cases", h2))
    data = [["ID", "Category", "Name", "Status", "Severity"]] + [
        [c["case_id"], CATEGORIES.get(c["category"], c["category"])[:26], Paragraph(_clean(c["name"], 60), body), c["status"], c["severity"]]
        for c in report["test_cases"]]
    tc = Table(data, colWidths=[16 * mm, 45 * mm, 62 * mm, 25 * mm, 22 * mm], repeatRows=1)
    tc.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#B8C2BD")),
                            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#DCE3E0")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    s.append(tc)
    s.append(Spacer(1, 10))
    s.append(Paragraph(_clean(report["disclaimer"], 900), body))
    doc.build(s)
    return out.getvalue()
